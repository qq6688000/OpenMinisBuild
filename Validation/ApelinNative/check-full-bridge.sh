#!/bin/sh
# Standalone ObjC check, not Swift importer or full-app build evidence.
set -eu
root=$(CDPATH= cd -- "$(dirname "$0")/../.." && pwd)
cd "$root"
sdk=${SDKROOT:-/opt/theos/sdks/iPhoneOS16.5.sdk}
cc=${CLANG:-clang}
missing=0
for header in deps/include/ish/ish.h deps/include/ish/kernel/native_offload.h deps/frameworks/Rclone.xcframework/ios-arm64/Headers/librclone.h; do
    if [ ! -f "$header" ]; then
        echo "BLOCKED: missing real generated/exported header: $header" >&2
        missing=1
    fi
done
if [ "$missing" -ne 0 ]; then
    echo 'Run deps/build_ish.sh and deps/build_rclone_ios.sh with Xcode first; no substitute headers are generated by this check.' >&2
    exit 77
fi
# Match target exported-header roots. Xcode header maps also resolve headers
# in these source groups; plain clang needs their directories explicitly.
"$cc" -target arm64-apple-ios16.0 -isysroot "$sdk" -fobjc-arc -fblocks \
    -I deps/include -I deps/include/ish \
    -I src/ios -I src/ios/iSH -I src/ios/NativeOffloads \
    -I src/ios/Debug -I src/ios/Diagnostics -I src/ios/Shared \
    -I src/ios/Vendor/cppjieba/include \
    -I deps/frameworks/FFmpeg.framework/Headers \
    -I deps/frameworks/Rclone.xcframework/ios-arm64/Headers \
    -x objective-c-header -fsyntax-only src/ios/MinisApp-Bridging-Header.h
echo 'PASS: full ObjC bridging header syntax only; Swift importer and app link remain separate.'
