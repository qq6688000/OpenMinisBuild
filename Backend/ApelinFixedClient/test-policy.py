#!/usr/bin/env python3
"""Patch verification and policy model only; Swift/device execution is separate."""
import argparse
import importlib.util
from pathlib import Path
import shutil
import subprocess
import tempfile

BASE=Path(__file__).resolve().parent

def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('upstream',type=Path)
    a=p.parse_args(argv)
    spec=importlib.util.spec_from_file_location('prepare_fixed',BASE/'prepare.py')
    module=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    patch=module.patch(a.upstream)
    assert patch==(BASE/'fixed-client.patch').read_text(), 'checked-in patch differs'
    peer='Apelind/PeerAuthenticator.swift'
    with tempfile.TemporaryDirectory(prefix='fixed-policy-') as tmp:
        root=Path(tmp)
        (root/'Apelind').mkdir()
        shutil.copyfile(a.upstream/peer,root/peer)
        subprocess.run(['git','apply','--check',str(BASE/'fixed-client.patch')],cwd=root,check=True)
        subprocess.run(['git','apply',str(BASE/'fixed-client.patch')],cwd=root,check=True)
        source=(root/peer).read_text()
        original=(a.upstream/peer).read_text()
        assert source==original.replace(module.OLD,module.NEW)
        assert 'Self.requiredEntitlements.allSatisfy' in source
        assert 'xpc_get_type(value) == AppXPC.typeBool && xpc_bool_get_value(value)' in source
        assert 'return (originalClient || minisClient) && isRootOwnedExecutable(path)' in source
        assert 'minis_expected_cdhash' not in source # Explicit unresolved security gate.
    # Logical table of the unchanged checks and additional exact path gate.
    # This is a model of the patch; it does not run Swift or authenticate a peer.
    def allowed(uid=501,pid=10,required=True,path='fixed',extra=True,owned=True):
        return pid>1 and uid in (0,501) and required and owned and (path=='original' or (path=='fixed' and extra))
    cases=[('fixed mobile',{},True),('fixed root',{'uid':0},True),
        ('original preserved',{'path':'original','extra':False},True),
        ('container',{'path':'container'},False),('prefix sibling',{'path':'fixed.evil'},False),
        ('other uid',{'uid':502},False),('invalid pid',{'pid':1},False),
        ('original entitlement missing',{'required':False},False),
        ('additional entitlement missing',{'extra':False},False),
        ('untrusted file ownership or mode',{'owned':False},False)]
    for name,kwargs,want in cases:
        assert allowed(**kwargs)==want,name
    result=subprocess.run(['python3',str(BASE/'package-client.py'),'unused','unused','--flavor','rootless'],capture_output=True,text=True)
    assert result.returncode != 0 and 'NON-DEPLOYABLE' in result.stderr
    print(f'PASS: pinned patch regenerated byte-identically; git apply --check/apply; unchanged original guards; {len(cases)} model cases; package gate rejects.')
    print('BLOCKED: patch has no final signed CDHash gate. No Swift/kernel/device result claimed.')

if __name__=='__main__':
    main()
